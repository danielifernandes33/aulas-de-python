'''
Escreva um programa que peça ao usuário uma letra e imprima se é uma vogal ou consoante.
'''

#Entrada de dados:
letra = input('Digite uma letra: ').strip().lower()

if letra == 'a':
    print('Esta letra é uma vogal')
elif letra == 'e':
    print('Esta letra é uma vogal')
elif letra == 'i':
    print('Esta letra é uma vogal')
elif letra == '0':
    print('Esta letra é uma vogal')
elif letra == 'u':
    print('Esta letra é uma vogal')
else:
    print('Esta letra é uma consoante')



